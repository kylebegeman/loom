import * as NodeCrypto from "node:crypto";
import type { EnclosurePlan } from "./plan.ts";
import { facingVector } from "./geometry.ts";
export const literal = (value: unknown): string =>
  JSON.stringify(value, (_key, v: unknown) =>
    typeof v === "number" ? Math.round(v * 10000) / 10000 : v,
  );
export function generatedSource(body: string, language: "openscad" | "build123d") {
  return `${language === "openscad" ? "//" : "#"} loom-generated: sha256=${NodeCrypto.createHash("sha256").update(body).digest("hex")}\n${body}`;
}
export function isUnedited(source: string) {
  const match = /^(?:\/\/|#) loom-generated: sha256=([a-f0-9]{64})\r?\n/.exec(source);
  return (
    !!match &&
    NodeCrypto.createHash("sha256").update(source.slice(match[0].length)).digest("hex") === match[1]
  );
}
export function writeScad(p: EnclosurePlan, design: string) {
  const params = p.params,
    hole = p.standoffs[0],
    common = p.standoffs.every((h) => h.diameter === hole?.diameter && h.pilot === hole?.pilot);
  const body = `// Case for ${design.replace(/[\r\n]/g, " ")}.
// Generated by Loom. Edit freely; regenerating preserves edited files.
/* [Show] */
part = "fit"; // [fit, base, lid]
/* [Case] */
wall = ${literal(params.wallMm)}; // [0.8:0.1:10]
floor_thickness = ${literal(params.floorMm)}; // [0.8:0.1:10]
lid_thickness = ${literal(params.lidMm)}; // [0.8:0.1:10]
corner_radius = ${literal(params.cornerRadiusMm)}; // [0:0.5:20]
/* [Fit] */
side_gap = ${literal(params.sideGapMm)}; // [0:0.1:10]
top_gap = ${literal(params.topGapMm)}; // [0:0.1:30]
standoff_height = ${literal(params.standoffHeightMm)}; // [0:0.5:50]
standoff_diameter = ${literal(common ? (hole?.diameter ?? 6) : 1)}; // [0.1:0.1:20]
pilot_diameter = ${literal(common ? (hole?.pilot ?? 2.6) : 1)}; // [0:0.1:10]
cutout_margin = ${literal(params.cutoutMarginMm)}; // [0:0.1:5]
lid_lip = ${literal(params.lidLipMm)}; // [0:0.1:10]
lid_lip_gap = ${literal(params.lidLipGapMm)}; // [0:0.05:2]
/* [Hidden] */
board_outline = ${literal(p.outline)};
board_bottom = ${literal(p.boardBottom)};
board_thickness = ${literal(p.thickness)};
parts_above = ${literal(p.partsAbove)};
holes = ${literal(p.standoffs.map((h) => [h.x, h.y, common ? 1 : h.diameter, common ? 1 : h.pilot]))};
cutouts = ${literal(p.cutouts.map((c) => [...c.box.min.map((v) => v + params.cutoutMarginMm), ...c.box.max.map((v) => v - params.cutoutMarginMm), ...facingVector(c.facing).slice(0, 2)]))};
proxies = ${literal(p.proxies.map((b) => [...b.min, ...b.max]))};
$fn = 48;
floor_top = board_bottom - standoff_height;
case_bottom = floor_top - floor_thickness;
lid_bottom = board_bottom + board_thickness + parts_above + top_gap;
module shape(grow) { offset(r=corner_radius) offset(delta=grow-corner_radius) polygon(board_outline); }
module box(b, margin=0) { translate([b[0]-margin,b[1]-margin,b[2]-margin]) cube([b[3]-b[0]+2*margin,b[4]-b[1]+2*margin,b[5]-b[2]+2*margin]); }
module openings() { for(b=cutouts) hull() { box(b,cutout_margin); translate([25*b[6],25*b[7],0]) box(b,cutout_margin); } }
module base() { difference() {
  union() {
    difference() {
      translate([0,0,case_bottom]) linear_extrude(lid_bottom-case_bottom) shape(side_gap+wall);
      translate([0,0,floor_top]) linear_extrude(lid_bottom-floor_top+0.1) shape(side_gap);
    }
    for(h=holes) translate([h[0],h[1],floor_top-0.01]) cylinder(h=standoff_height+0.01,d=standoff_diameter*h[2]);
  }
  for(h=holes) if(pilot_diameter*h[3]>0) translate([h[0],h[1],case_bottom-0.1]) cylinder(h=board_bottom-case_bottom+0.2,d=pilot_diameter*h[3]);
  openings();
} }
module lid() { difference() { union() {
  translate([0,0,lid_bottom]) linear_extrude(lid_thickness) shape(side_gap+wall);
  if(lid_lip>0) translate([0,0,lid_bottom-lid_lip]) linear_extrude(lid_lip) difference() { shape(side_gap-lid_lip_gap); shape(side_gap-lid_lip_gap-wall); }
} openings(); } }
module board_proxy() { color("green") translate([0,0,board_bottom]) linear_extrude(board_thickness) polygon(board_outline); color("grey") for(b=proxies) box(b); }
if(part=="base") base(); else if(part=="lid") lid(); else {base(); translate([0,0,10]) lid(); board_proxy();}
`;
  return generatedSource(body, "openscad");
}
